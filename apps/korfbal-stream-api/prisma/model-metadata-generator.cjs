#!/usr/bin/env node
/*
 * A tiny Prisma generator (second generator block in schema.prisma, run by every `prisma generate`).
 * Prisma 7 removed `Prisma.dmmf`, and the client's runtime data model has no `isList` or
 * `relationFromFields`, which the tenant scope (src/services/tenantScope.ts) needs. This writes the
 * parts it uses from the schema's DMMF to src/generated/model-metadata.ts.
 *
 * A generator speaks JSON-RPC over stdin (requests) and stderr (replies; stdout is for logs), one JSON message per line.
 */
const fs = require('node:fs');
const path = require('node:path');
const readline = require('node:readline');

function reply(id, result) {
  process.stderr.write(`${JSON.stringify({jsonrpc: '2.0', id, result})}\n`);
}

function generate(options) {
  const dir = options.generator.output.value;
  const models = options.dmmf.datamodel.models.map((model) => ({
    name: model.name,
    fields: model.fields.map((f) => ({
      name: f.name,
      kind: f.kind,
      type: f.type,
      isList: f.isList,
      relationName: f.relationName ?? null,
      relationFromFields: f.relationFromFields ?? [],
    })),
  }));
  fs.mkdirSync(dir, {recursive: true});
  const source = [
    '// Generated by prisma/model-metadata-generator.cjs (`npm run prisma:generate`): do not edit.',
    'export interface ModelField {name: string; kind: string; type: string; isList: boolean; relationName: string | null; relationFromFields: string[]}',
    'export interface ModelMetadata {name: string; fields: ModelField[]}',
    `export const modelMetadata: ModelMetadata[] = ${JSON.stringify(models, null, 2)};`,
    '',
  ].join('\n');
  fs.writeFileSync(path.join(dir, 'index.ts'), source);
}

readline.createInterface({input: process.stdin}).on('line', (line) => {
  const {id, method, params} = JSON.parse(line);
  if (method === 'getManifest') {
    reply(id, {manifest: {prettyName: 'Model metadata', defaultOutput: 'model-metadata', requiresGenerators: [], requiresEngines: []}});
  } else if (method === 'generate') {
    generate(params);
    reply(id, null);
  }
});
